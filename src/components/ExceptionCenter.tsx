import React from "react";
import {
    AlertTriangle,
    ArrowRight,
    CheckCircle2,
    ShieldAlert
} from "lucide-react";

import type { BusinessException } from "../core/ruleEngine";

type Props = {
    exceptions: BusinessException[];
    onReview: (entityId: string) => void;
};

const priorityLabel = (
    priority: BusinessException["priority"]
): string => {
    switch (priority) {
        case "critical":
            return "Critical";
        case "high":
            return "High";
        case "medium":
            return "Medium";
        case "low":
            return "Low";
        default:
            return priority;
    }
};

const ExceptionCenter = ({
    exceptions,
    onReview
}: Props): React.JSX.Element => {
    if (exceptions.length === 0) {
        return (
            <section className="exception-center">
                <div className="section-head">
                    <h2>Exception Center</h2>
                    <p>
                        Live business rules are currently
                        clear.
                    </p>
                </div>

                <div className="exception-empty">
                    <CheckCircle2 size={22} />

                    <div>
                        <strong>
                            No active exceptions
                        </strong>

                        <p>
                            The rule engine has no triggered
                            business exceptions requiring
                            attention.
                        </p>
                    </div>
                </div>
            </section>
        );
    }

    return (
        <section className="exception-center">
            <div className="section-head">
                <div>
                    <h2>Exception Center</h2>

                    <p>
                        Live exceptions generated by
                        business rules.
                    </p>
                </div>

                <span className="exception-count">
                    {exceptions.length} active
                </span>
            </div>

            <div className="exception-list">
                {exceptions.map(exception => (
                    <article
                        className="exception-card"
                        key={exception.id}
                    >
                        <div
                            className={`exception-icon ${exception.priority}`}
                        >
                            {exception.priority ===
                                "critical" ? (
                                <ShieldAlert size={19} />
                            ) : (
                                <AlertTriangle size={19} />
                            )}
                        </div>

                        <div className="exception-content">
                            <div className="exception-header">
                                <strong>
                                    {exception.title}
                                </strong>

                                <span
                                    className={`exception-priority ${exception.priority}`}
                                >
                                    {priorityLabel(
                                        exception.priority
                                    )}
                                </span>
                            </div>

                            <p>
                                {exception.detail}
                            </p>

                            <div className="exception-meta">
                                <span>
                                    Entity:{" "}
                                    <strong>
                                        {exception.entityId}
                                    </strong>
                                </span>

                                <span>
                                    Rule:{" "}
                                    <strong>
                                        {exception.ruleId}
                                    </strong>
                                </span>

                                <span>
                                    Stage:{" "}
                                    <strong>
                                        {exception.stageId}
                                    </strong>
                                </span>
                            </div>

                            <div className="exception-actions">
                                {exception.actionTypes.map(
                                    action => (
                                        <span
                                            className="exception-action"
                                            key={action}
                                        >
                                            {action}
                                        </span>
                                    )
                                )}

                                <button
                                    type="button"
                                    className="secondary"
                                    onClick={() => onReview(exception.entityId)}
                                >
                                    Review
                                    <ArrowRight size={14} />
                                </button>
                            </div>
                        </div>
                    </article>
                ))}
            </div>
        </section>
    );
};

export default ExceptionCenter;